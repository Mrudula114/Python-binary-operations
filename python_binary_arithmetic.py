def to_8bit(n):
    return format(n & 0xFF, '08b')


def signed_value(n):
    if n >= 128:
        return n - 256
    return n


def add(a, b):
    A = a & 0xFF
    B = b & 0xFF
    total = A + B
    result = total & 0xFF

    overflow = ((a >= 0 and b >= 0 and signed_value(result) < 0) or
                (a < 0 and b < 0 and signed_value(result) >= 0))

    print("First operand :", to_8bit(a))
    print("Second operand:", to_8bit(b))
    print("Binary addition:")
    print(" ", to_8bit(a))
    print("+", to_8bit(b))
    print("---------")
    print(" ", to_8bit(result))
    print("Decimal result:", signed_value(result))
    print("Overflow:", "Yes" if overflow else "No")
    print()


