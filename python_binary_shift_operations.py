# a) Logical left shift
num1 = "10110110"
print("Logical Left Shift")
print("Original number:", num1)

step1 = num1[1:] + "0"
print("After 1 position:", step1)

step2 = step1[1:] + "0"
print("After 2 positions:", step2)

print("Final result:", step2)
print("Verification:", format((int(num1, 2) << 2) & 255, '08b'))

print()

# b) Logical right shift
num2 = "11010100"
print("Logical Right Shift")
print("Original number:", num2)

step1 = "0" + num2[:-1]
print("After 1 position:", step1)

step2 = "0" + step1[:-1]
print("After 2 positions:", step2)

print("Final result:", step2)
print("Verification:", format(int(num2, 2) >> 2, '08b'))